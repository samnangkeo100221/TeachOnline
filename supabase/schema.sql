-- 3. Table: teach_online_lessons (Lessons & Video Links)
CREATE TABLE IF NOT EXISTS teach_online_lessons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_name TEXT NOT NULL,
  level TEXT NOT NULL,
  title TEXT DEFAULT '',
  duration_minutes INTEGER DEFAULT 60,
  video_link1 TEXT DEFAULT '',
  video_link2 TEXT DEFAULT '',
  objectives TEXT DEFAULT '',
  content TEXT DEFAULT '',
  formula_summary TEXT DEFAULT '',
  examples TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  common_errors TEXT DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
  UNIQUE(lesson_name, level)
);

-- 4. Table: teach_online_questions (Question Bank)
CREATE TABLE IF NOT EXISTS teach_online_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson TEXT NOT NULL,
  level TEXT NOT NULL,
  type TEXT NOT NULL,
  question_title TEXT DEFAULT '',
  question_text TEXT DEFAULT '',
  language TEXT DEFAULT 'en-US',
  audio_language TEXT DEFAULT 'en-US',
  correct_answer TEXT DEFAULT '',
  options TEXT DEFAULT '',
  data_extra TEXT DEFAULT '',
  category TEXT DEFAULT '',
  points NUMERIC DEFAULT 1,
  speech_text TEXT DEFAULT '',
  media_url TEXT DEFAULT '',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 5. Table: teach_online_results (Student Exam Submissions)
CREATE TABLE IF NOT EXISTS teach_online_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_name TEXT NOT NULL,
  lesson TEXT NOT NULL,
  level TEXT NOT NULL,
  score NUMERIC NOT NULL DEFAULT 0,
  total_points NUMERIC NOT NULL DEFAULT 0,
  percentage NUMERIC NOT NULL DEFAULT 0,
  submission_date TEXT NOT NULL,
  submission_time TEXT NOT NULL,
  detailed_reviews JSONB DEFAULT '[]'::jsonb,
  synced_to_sheet BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Enable Row Level Security (RLS) and grant public anon read/write
-- so frontend web app can interact with Supabase using the Anon public key
ALTER TABLE teach_online_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE teach_online_students ENABLE ROW LEVEL SECURITY;
ALTER TABLE teach_online_lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE teach_online_questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE teach_online_results ENABLE ROW LEVEL SECURITY;

-- Allow anon full access (SELECT, INSERT, UPDATE, DELETE) for easy usage
CREATE POLICY "Allow public all access on settings" ON teach_online_settings FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on students" ON teach_online_students FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on lessons" ON teach_online_lessons FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on questions" ON teach_online_questions FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public all access on results" ON teach_online_results FOR ALL USING (true) WITH CHECK (true);
